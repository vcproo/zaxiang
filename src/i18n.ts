export type Lang = 'zh' | 'en';

const base = () => import.meta.env.BASE_URL.replace(/\/$/, '');

export function langFromPath(pathname: string): Lang {
  let path = pathname.startsWith(base()) ? pathname.slice(base().length) || '/' : pathname;
  if (!path.startsWith('/')) path = '/' + path;
  return path === '/en' || path.startsWith('/en/') ? 'en' : 'zh';
}

/** 同一页面的另一种语言地址。保留路径，不带查询串和 hash（hash 由页头脚本补上）。 */
export function switchPath(pathname: string, target: Lang) {
  let path = pathname.startsWith(base()) ? pathname.slice(base().length) || '/' : pathname;
  if (!path.startsWith('/')) path = '/' + path;
  if (path === '/en' || path === '/en/') path = '/';
  else if (path.startsWith('/en/')) path = path.slice(3);
  if (path.length > 1 && !path.endsWith('/')) path += '/';
  if (target === 'zh') return base() + (path === '/' ? '/' : path);
  return base() + (path === '/' ? '/en/' : '/en' + path);
}

/** 去掉 base 和语言前缀，用来判断导航高亮。 */
export function barePath(pathname: string) {
  let path = pathname.startsWith(base()) ? pathname.slice(base().length) || '/' : pathname;
  if (!path.startsWith('/')) path = '/' + path;
  if (path === '/en' || path === '/en/') return '/';
  if (path.startsWith('/en/')) path = path.slice(3);
  return path || '/';
}

